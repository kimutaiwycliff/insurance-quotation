#!/usr/bin/env python3
"""Generate the app's help guide from the web's (apps/web/src/components/help/topics.ts), so both say the same.

Usage (from apps/android): python3 scripts/generate_help.py
Needs Node 22.6+ (it reads the TypeScript with --experimental-strip-types).
"""

from __future__ import annotations

import json
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[3]
OUT = pathlib.Path(__file__).resolve().parents[1] / "app/src/main/java/app/brokeros/android/core/HelpTopics.kt"

raw = subprocess.run(
    ["node", "--experimental-strip-types", "--no-warnings", "-e",
     "import('./apps/web/src/components/help/topics.ts').then(m => console.log(JSON.stringify({areas: m.AREAS, topics: m.TOPICS})))"],
    cwd=ROOT, check=True, capture_output=True, text=True,
).stdout
data = json.loads(raw)


def k(value: str | None) -> str:
    return "null" if value is None else json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def ks(values: list[str] | None) -> str:
    return "emptyList()" if not values else "listOf(" + ", ".join(k(v) for v in values) + ")"


lines = [
    "// Generated by scripts/generate_help.py from apps/web/src/components/help/topics.ts. Do not edit by hand.",
    "package app.brokeros.android.core",
    "",
    "data class HelpArea(val key: String, val title: String, val blurb: String)",
    "",
    "data class HelpTopic(",
    "    val id: String,",
    "    val area: String,",
    "    val title: String,",
    "    val summary: String,",
    "    val steps: List<String>,",
    "    val tip: String?,",
    "    /** The web page this topic points to (the app maps it to its own screen when there is one). */",
    "    val href: String?,",
    "    val linkLabel: String?,",
    "    val keywords: List<String>,",
    "    val feature: String?,",
    "    val anyOf: List<String>,",
    ")",
    "",
    "val HELP_AREAS = listOf(",
]
lines += [f"    HelpArea({k(a['key'])}, {k(a['title'])}, {k(a['blurb'])})," for a in data["areas"]]
lines += [")", "", "val HELP_TOPICS = listOf("]
for t in data["topics"]:
    lines.append(
        "    HelpTopic(\n"
        f"        {k(t['id'])}, {k(t['area'])}, {k(t['title'])},\n"
        f"        {k(t['summary'])},\n"
        f"        steps = {ks(t.get('steps'))},\n"
        f"        tip = {k(t.get('tip'))}, href = {k(t.get('href'))}, linkLabel = {k(t.get('linkLabel'))},\n"
        f"        keywords = {ks(t.get('keywords'))}, feature = {k(t.get('feature'))}, anyOf = {ks(t.get('anyOf'))},\n"
        "    ),"
    )
lines += [")", ""]
OUT.write_text("\n".join(lines))
print(f"Wrote {len(data['topics'])} topics to {OUT.relative_to(ROOT)}")
